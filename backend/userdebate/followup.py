"""Answers a reader's follow-up question about ONE debate, from that debate's own stored material.

The context is rebuilt from the stored record on every call (never from the browser), so an answer can only draw on the
debate named in the URL, and ids the model cites are checked against that debate's real claims and sources."""
import re  # regular expressions (pattern matching on text)

from .schemas import PERSONA_LABELS, PERSONAS  # analyst names

# Most characters of debate material sent to the model.
MAX_CONTEXT_CHARS = 9000
# Citation tokens look like [left-1] or [S2]. Anything shaped like that is checked: ids that do not exist are removed.
_REFERENCE = re.compile(r"\[([A-Za-z]+-\d+|S\d+)\]")


# Builds the debate material for the prompt and the set of ids the answer may legitimately cite.
def build_context(record: dict) -> tuple[str, set[str]]:
    ids: set[str] = set()
    parts = [f"Debate question: {record.get('question') or record.get('topic', '')}"]
    perspectives = record.get("perspectives") or {}
    for persona in PERSONAS:
        state = perspectives.get(persona)
        content = state.get("content") if state else None
        if not content:
            continue
        lines = [
            f"\n[{persona}] {PERSONA_LABELS[persona]} - position: {content['position_summary']}",
            f"  Strongest argument: {content['strongest_argument']}",
            f"  Strongest counterargument to its own position: {content['counterargument']}",
        ]
        for claim in content["claims"]:
            ids.add(claim["id"])
            cited = f" (sources: {', '.join(claim['source_ids'])})" if claim["source_ids"] else ""
            lines.append(f"  [{claim['id']}] ({claim['type']}, {claim['status']}) {claim['text']}{cited}")
        for label, key in (("Assumptions", "assumptions"), ("Uncertainties", "uncertainties")):
            if content[key]:
                lines.append(f"  {label}: " + "; ".join(content[key]))
        parts.append("\n".join(lines))
    # Debates generated by the daily job have plain text instead of structured perspectives.
    if not ids:
        for persona, text in (record.get("arguments") or {}).items():
            parts.append(f"\n[{persona}] opening argument: {text}")
            rebuttal = (record.get("rebuttals") or {}).get(persona)
            if rebuttal:
                parts.append(f"[{persona}] rebuttal: {rebuttal}")
    disagreements = record.get("disagreements") or {}
    if disagreements and "error" not in disagreements:
        parts.append("\nDisagreement map:")
        if disagreements.get("central_question"):
            parts.append(f"  Central question: {disagreements['central_question']}")
        for group in ("agreements", "interpretations", "conflicts", "unresolved", "evidence_needed"):
            for item in disagreements.get(group, []):
                parts.append(f"  {group} - {item['summary']} (claims: {', '.join(item['claim_ids']) or 'none'})")
    verdict = record.get("verdict_data") or {}
    if verdict:
        parts.append("\nModerator verdict:")
        for key in ("summary", "evidence_supports", "strongest_counterargument",
                    "conflicting_or_insufficient_evidence", "reasoning", "conclusion"):
            if verdict.get(key):
                parts.append(f"  {key}: {verdict[key]}")
        parts.append(f"  evidence_sufficiency: {verdict.get('evidence_sufficiency')}")
        parts.append("  could_change_conclusion: " + "; ".join(verdict.get("could_change_conclusion", [])))
        parts.append("  limitations: " + "; ".join(verdict.get("limitations", [])))
    elif record.get("verdict"):
        parts.append(f"\nModerator verdict: {record['verdict']}")
    sources = record.get("sources") or []
    if sources:
        parts.append("\nSources (related news coverage, not verified evidence):")
        for source in sources:
            ids.add(source["id"])
            parts.append(f"  [{source['id']}] {source['title']} ({source['publisher']}, {source['published_at']}): "
                         f"{source['excerpt']}")
    else:
        parts.append("\nNo external sources were retrieved for this debate.")
    return "\n".join(parts)[:MAX_CONTEXT_CHARS], ids


# Removes citation tokens that do not point at a real claim or source of this debate, and lists the valid ones used.
def clean_references(answer: str, valid_ids: set[str]) -> tuple[str, list[str]]:
    used: list[str] = []

    def keep(match: re.Match) -> str:
        reference = match.group(1)
        if reference not in valid_ids:
            return ""
        if reference not in used:
            used.append(reference)
        return match.group(0)

    cleaned = _REFERENCE.sub(keep, answer)
    return re.sub(r"[ \t]{2,}", " ", cleaned).strip(), used
