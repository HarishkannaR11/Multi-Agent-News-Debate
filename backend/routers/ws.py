import logging  # Python's built-in logging system

from fastapi import APIRouter, WebSocket, WebSocketDisconnect  # router, WebSocket connection, disconnect error

from ..services.redis_service import get_debate, parse_debate_id, resolve_debate_id  # Redis helpers

# A logger named after this module.
logger = logging.getLogger(__name__)

# A group of endpoints (this one has no common prefix).
router = APIRouter()

# WebSocket close code we use to mean "debate not found" (4000-4999 are free for apps to define).
NOT_FOUND_CLOSE_CODE = 4404


# WebSocket endpoint: /ws/debate/{debate_id}
@router.websocket("/ws/debate/{debate_id}")
async def debate_ws(websocket: WebSocket, debate_id: str):
    """Replay a stored debate stage by stage.

    Debates are generated by the daily job (or the protected admin endpoint), never
    by a browser connection, so opening a page can't trigger paid LLM calls.
    """
    # Accept the browser's connection request.
    await websocket.accept()
    # Turn the client's id ("latest", a date, or a full id) into a real stored id.
    resolved = await resolve_debate_id(debate_id)
    # Split it into (date, slug), if there is one.
    parsed = parse_debate_id(resolved) if resolved else None
    # Load the debate from Redis, if we have a valid id.
    debate = await get_debate(*parsed) if parsed else None
    # Nothing found: tell the client, close with our special code, and stop.
    if not resolved or not debate:
        await websocket.send_json({"error": "not_found", "message": "No debate found for this id."})
        await websocket.close(code=NOT_FOUND_CLOSE_CODE)
        return

    # Fields included in every message.
    base = {"debate_id": resolved, "topic": debate["topic"]}
    # If the browser disconnects while we are sending, it raises WebSocketDisconnect (handled below).
    try:
        # Message 1: the opening arguments (rebuttals and verdict not shown yet).
        await websocket.send_json({
            **base, "node": "replay", "status": "debating",
            "data": debate["arguments"], "rebuttals": {}, "verdict": "", "bias_scores": {},
        })
        # Message 2: openings plus rebuttals.
        await websocket.send_json({
            **base, "node": "replay", "status": "rebuttal",
            "data": debate["arguments"], "rebuttals": debate["rebuttals"], "verdict": "", "bias_scores": {},
        })
        # Message 3: everything, including the verdict and bias scores.
        await websocket.send_json({
            **base, "node": "replay", "status": "done",
            "data": debate["arguments"], "rebuttals": debate["rebuttals"],
            "verdict": debate["verdict"], "bias_scores": debate["bias_scores"],
            # The optional second round (empty for debates that did not have one).
            "focus": debate.get("focus", ""), "crossfire": debate.get("crossfire", {}),
        })
        # Normal close: the replay is finished.
        await websocket.close()
    # The browser left early; that is fine, so just stop quietly.
    except WebSocketDisconnect:
        pass
